def feature_type(column: str) -> str:
    """Тип признака модели по спискам выше

    Незнакомую колонку не угадываем, а сообщаем об ошибке
    """
    for kind, columns in (
        ("количественный", QUANTITATIVE),
        ("бинарный", BINARY),
        ("порядковый", ORDINAL),
        ("номинальный", NOMINAL),
    ):
        if column in columns:
            return kind
    raise ValueError(f"{column!r} не входит в признаки модели")


